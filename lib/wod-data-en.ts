function tr(text: string): string {
  return RULES.reduce((acc, [re, to]) => acc.replace(re, to), text)
}

export function localizeWod(wod: WOD, locale: string): WOD {
  if (locale !== 'en') return wod
  return {
    ...wod,
    description: tr(wod.description),
    scaling: tr(wod.scaling),
    timeTarget: tr(wod.timeTarget),
    tags: wod.tags.map(tr),
  }
}

/** Dev helper: returns the WOD fields that still contain Hangul after localization. */
export function untranslatedWodFields(wods: WOD[]): string[] {
  const out: string[] = []
  for (const w of wods) {
    const l = localizeWod(w, 'en')
    const fields: [string, string][] = [
      ['description', l.description], ['scaling', l.scaling], ['timeTarget', l.timeTarget], ['tags', l.tags.join(' | ')],
    ]
    for (const [k, v] of fields) {
      if (/[ㄱ-힝]/.test(v)) out.push(`${w.id}.${k}: ${v.split('\n').filter((x) => /[ㄱ-힝]/.test(x)).join(' // ')}`)
    }
  }
  return out
}
